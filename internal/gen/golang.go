package main

import (
	"fmt"
	"go/format"
	"strings"
)

const generatedLine = "Code generated by internal/gen from schema/webhooks/events.schema.json. DO NOT EDIT."

func goType(described field) string {
	base := map[kind]string{
		kindText: "string", kindUUID: "string", kindTime: "time.Time", kindInteger: "int",
		kindTextList: "[]string", kindObject: described.Object,
	}[described.Kind]
	if described.Nullable {
		return "*" + base
	}
	return base
}

// goSource is the Go file of event types, payload structs and known values.
func goSource(schema model) ([]byte, error) {
	taken := names{}
	var out strings.Builder
	fmt.Fprintf(&out, "// %s\n\npackage webhooks\n\nimport \"time\"\n\n", generatedLine)

	out.WriteString("// The type of each event Cimento sends.\nconst (\n")
	for _, described := range schema.Events {
		part, err := goPart(described.Type)
		if err != nil {
			return nil, err
		}
		name := "EventType" + part
		if err := taken.claim(name, described.Type); err != nil {
			return nil, err
		}
		fmt.Fprintf(&out, "\t// %s\n\t%s = %q\n", described.Description, name, described.Type)
	}
	out.WriteString(")\n\n")

	for _, described := range schema.Payloads {
		if err := taken.claim(described.Name, described.Name); err != nil {
			return nil, err
		}
		fields := names{}
		fmt.Fprintf(&out, "type %s struct {\n", described.Name)
		for _, key := range described.Fields {
			name, err := goPart(key.Key)
			if err != nil {
				return nil, err
			}
			if err := fields.claim(name, described.Name+"."+key.Key); err != nil {
				return nil, err
			}
			fmt.Fprintf(&out, "\t%s %s `json:%q`\n", name, goType(key), key.Key)
		}
		out.WriteString("}\n\n")

		for _, key := range described.Fields {
			if key.Known == nil {
				continue
			}
			fmt.Fprintf(&out, "// The values %s.%s takes today. Others may be added.\nconst (\n", described.Name, goName(key.Key))
			for _, value := range key.Known {
				part, err := goPart(value)
				if err != nil {
					return nil, fmt.Errorf("%s.%s: %w", described.Name, key.Key, err)
				}
				name := described.Name + goName(key.Key) + part
				if err := taken.claim(name, described.Name+"."+key.Key+" "+value); err != nil {
					return nil, err
				}
				fmt.Fprintf(&out, "\t%s = %q\n", name, value)
			}
			out.WriteString(")\n\n")
		}
	}

	out.WriteString("// newPayload is an empty payload of the struct eventType's data is read\n// into, and whether eventType is one this package knows.\n")
	out.WriteString("func newPayload(eventType string) (any, bool) {\n\tswitch eventType {\n")
	for _, described := range schema.Payloads {
		var cases []string
		for _, sent := range schema.Events {
			if sent.Payload == described.Name {
				cases = append(cases, "EventType"+goName(sent.Type))
			}
		}
		if len(cases) > 0 {
			fmt.Fprintf(&out, "\tcase %s:\n\t\treturn &%s{}, true\n", strings.Join(cases, ",\n\t\t"), described.Name)
		}
	}
	out.WriteString("\t}\n\treturn nil, false\n}\n")

	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return formatted, nil
}
